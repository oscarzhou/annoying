export const GROUP_TIME_ZONE = "Pacific/Auckland";

export function groupLocalDate(now: Date = new Date(), timeZone = GROUP_TIME_ZONE) {
  const parts = new Intl.DateTimeFormat("en-NZ", { timeZone, year: "numeric", month: "2-digit", day: "2-digit" }).formatToParts(now);
  const values = Object.fromEntries(parts.map((part) => [part.type, part.value]));
  return `${values.year}-${values.month}-${values.day}`;
}

export function addCalendarDays(date: string, days: number) {
  const value = new Date(`${date}T12:00:00Z`);
  value.setUTCDate(value.getUTCDate() + days);
  return value.toISOString().slice(0, 10);
}
